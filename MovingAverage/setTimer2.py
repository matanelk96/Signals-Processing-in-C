"""
setTimer2.py
Names: Matan Ronen & Matanel Kadosh

Generates SetTimer2_ADC_DAC.c/.h (Timer2 as the ADC sample clock, ADC, DAC)
for a given ADC sample rate.

Usage:
    py setTimer2.py <ADC_sample_rate>        (the book's 2026 value is 5000)

Timer2 counts up from the reload value to 65536, so
    ADC_sample_rate = Fosc / (65536 - reload)
    reload          = 65536 - round(Fosc / ADC_sample_rate)
"""
import datetime
import sys

FOSC = 11_059_200  # crystal frequency, Hz


def main():

    # Get the ADC_sample_rate from the user.
    if len(sys.argv) > 1:
        ADC_sample_rate = int(sys.argv[1])
    else:
        print("usage: py setTimer2.py <ADC_sample_rate>")
        return
    print("ADC_sample_rate: ", ADC_sample_rate)

    cycles = round(FOSC / ADC_sample_rate)
    timer_reload_value = 65536 - cycles
    if not 0 <= timer_reload_value <= 0xFFFF:
        print(f"error: {ADC_sample_rate} Hz is out of range for a 16-bit timer "
              f"(between {FOSC / 65536:.1f} Hz and {FOSC} Hz)")
        return
    actual_rate = FOSC / cycles
    print(f"reload = 0x{timer_reload_value:04X}, actual rate = {actual_rate:.1f} Hz")

    rcap2h = (timer_reload_value >> 8) & 0xFF
    rcap2l = timer_reload_value & 0x00FF

    with open("SetTimer2_ADC_DAC.c", "w") as f1:
        f1.write('#include "aduc841.h"\n'
                '#include "SetTimer2_ADC_DAC.h"\n\n')
        f1.write(
            "/* This code generated by setTimer2.py\n"
            f"   on {datetime.datetime.now()}\n"
            f"   ADC_sample_rate target {ADC_sample_rate} Hz, actual {actual_rate:.1f} Hz\n"
            "Names: Matan Ronen & Matanel Kadosh \n"
            "*/\n\n"
        )
        f1.write("void init_Timer2(void)\n{\n")
        f1.write("   T2CON = 0x00; // Timer2 in auto-reload, timer mode\n")
        f1.write(f"   RCAP2H = 0x{rcap2h:02X};\n")
        f1.write(f"   RCAP2L = 0x{rcap2l:02X};\n")
        f1.write("   TH2 = RCAP2H;\n")
        f1.write("   TL2 = RCAP2L;\n")
        f1.write("   TF2 = 0; // Clear overflow flag- must be cleared by the user\n")
        f1.write("   TR2 = 1; // Turns on Timer2\n")
        f1.write("}\n\n")
        f1.write(
                "void setADC(void)\n{\n"
                "   ADCCON1 = 0XBA; //10111010\n"
                "   CCONV = 1;       // continuous conversion, started by Timer2 overflow\n"
                "   ADCCON2 &= 0XF0; // Set ADC to channel 0\n"
                "   EADC = 1;        // Enable the ADC interrupt\n"
                "}\n\n"
                "void setDAC(void)\n{\n"
                "   DACCON = 0X19; // 0001 1001: 12-bit, range VREF, bit 2 (sync) cleared\n"
                "}\n\n"
            )

    with open("SetTimer2_ADC_DAC.h", "w") as f2:
        f2.write(
        "/* This code generated by setTimer2.py too\n"
            f"   on {datetime.datetime.now()}\n"
            "   An header file for SetTimer2_ADC_DAC.c\n"
            "Names: Matan Ronen & Matanel Kadosh \n"
            "*/\n\n"
            "void init_Timer2(void);\n"
            "void setADC(void);\n"
            "void setDAC(void);\n"
        )


if __name__ == '__main__':
    main()

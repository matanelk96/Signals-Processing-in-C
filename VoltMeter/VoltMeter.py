import datetime
import sys
import math

def main():

    #Get the baudrate from the user.
    if len(sys.argv) > 1:
        baudrate = int(sys.argv[1])
    else:
        print("usage: python VoltMeter.py <baudrate>")
        return

    #Calculate the T3CON and the T3FD for the baudrate which was got from user
    div = math.floor(math.log(11059200 / (16 * baudrate), 2))
    mone = 2 * 11059200
    mechane = (2 ** (div - 1)) * baudrate
    print(div)
    print("mone: ", mone)

    print("mechane: ", mechane)
    t3fd = math.floor((mone / mechane) - 64)



    with open('VoltTimer3.c', 'w') as f:
        f.write('#include "VoltTimer3.h"\n')
        f.write('#include "aduc841.h"\n\n')
        f.write(f'/* This code generated by VoltMeter.py\n on {datetime.datetime.now()}\n Baudrate {baudrate} for fcore = 11.0592Mhz */\n\n')
        f.write('void init_Timer3( void ) \n{ \n')
        f.write('  T3CON &= 0xFF; \n')
        f.write(f'  T3CON |= 0x8{div}; \n')
        f.write(f'  T3FD = {t3fd}; \n')
        f.write('}')


if __name__ == '__main__':
    main()


"""
fir_design.py
Names: Matan Ronen & Matanel Kadosh

Designs an ideal windowed-sinc FIR low-pass filter for the Chapter 22 lab and
writes the C coefficients to coeffs.h (stamped with the date/time it was
generated and our names).

Usage:
    python fir_design.py <corner_freq_Hz> <sample_rate_Hz> [alpha]

alpha (default 1.5) trades filter length for sharpness; the book suggests
values between 1 and about 2.

Only the standard library is required. If matplotlib happens to be installed,
a Bode plot of the filter (ideal vs. quantized coefficients) is also saved to
fir_bode.png, since the lab asks for one.
"""
import cmath
import datetime
import math
import sys

FOSC = 11_059_200  # crystal frequency, Hz
NAMES = "Matan Ronen & Matanel Kadosh"


def design(f, Fs, alpha=1.5):
    """Return (N, scale_factor, ideal_h, scaled_h) for k = -N..N."""
    delta_f = min(2 * f, Fs - 2 * f)          # width of the narrowest feature
    N = math.ceil(alpha * Fs / delta_f)
    Ts = 1.0 / Fs
    ideal = []
    for k in range(-N, N + 1):
        if k == 0:
            ideal.append(2 * f / Fs)
        else:
            x = 2 * math.pi * f * k * Ts
            ideal.append((2 * f / Fs) * math.sin(x) / x)
    # Integer scale factor, so that the C code divides by exactly the factor
    # used here. floor() guarantees the largest coefficient fits in a signed char.
    scale_factor = int(math.floor(127.0 / max(abs(c) for c in ideal)))
    scaled = [int(round(c * scale_factor)) for c in ideal]
    return N, scale_factor, ideal, scaled


def response_db(coeffs, Fs, points=512):
    """Magnitude response (dB) of the symmetric filter on 0..Fs/2."""
    freqs, mags = [], []
    for i in range(points):
        fr = (Fs / 2) * i / (points - 1)
        h = sum(c * cmath.exp(-2j * math.pi * fr * m / Fs) for m, c in enumerate(coeffs))
        freqs.append(fr)
        mags.append(20 * math.log10(max(abs(h), 1e-9)))
    return freqs, mags


def save_bode(ideal, scaled, scale_factor, Fs):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed - skipping the Bode plot.")
        return
    fr, ideal_db = response_db(ideal, Fs)
    _, quant_db = response_db([c / scale_factor for c in scaled], Fs)
    plt.figure()
    plt.semilogx(fr[1:], ideal_db[1:], label="ideal coefficients")
    plt.semilogx(fr[1:], quant_db[1:], "--", label="rescaled char coefficients")
    plt.xlabel("Frequency [Hz]")
    plt.ylabel("Magnitude [dB]")
    plt.grid(True, which="both")
    plt.legend()
    plt.savefig("fir_bode.png", dpi=120)
    print("Wrote fir_bode.png")


def main():
    if len(sys.argv) < 3:
        print("usage: python fir_design.py <corner_freq_Hz> <sample_rate_Hz> [alpha]")
        return
    f = float(sys.argv[1])
    Fs = float(sys.argv[2])
    alpha = float(sys.argv[3]) if len(sys.argv) > 3 else 1.5

    N, scale_factor, ideal, scaled = design(f, Fs, alpha)
    num_coeff = 2 * N + 1
    print(f"f={f} Hz, Fs={Fs} Hz, alpha={alpha}  ->  N={N}, NUM_COEFF={num_coeff}, SCALE_FACTOR={scale_factor}")

    with open("coeffs.h", "w") as out:
        out.write("/*\n")
        out.write("File: coeffs.h\n")
        out.write(f"Names: {NAMES}\n")
        out.write("This code generated by fir_design.py -- do not edit by hand, regenerate instead.\n")
        out.write(f"   on {datetime.datetime.now()}\n")
        out.write(f"   corner frequency f = {f} Hz, sample rate Fs = {Fs} Hz, alpha = {alpha}\n")
        out.write("*/\n\n")
        out.write(f"#define N {N}\n")
        out.write(f"#define NUM_COEFF {num_coeff}\n")
        out.write(f"#define SCALE_FACTOR {scale_factor}\n\n")
        out.write(f"code char h[NUM_COEFF] = {{{', '.join(str(v) for v in scaled)}}};\n")
    print("Wrote coeffs.h")

    # Timer2 reload value for the new Fs: Fs = Fosc / (65536 - reload)
    reload_val = 65536 - round(FOSC / Fs)
    print(f"Timer2 reload for Fs={Fs} Hz: RCAP2H=0x{(reload_val >> 8) & 0xFF:02X}, "
          f"RCAP2L=0x{reload_val & 0xFF:02X}  (update SetTimer2_ADC_DAC.c)")

    save_bode(ideal, scaled, scale_factor, Fs)


if __name__ == "__main__":
    main()
